#!/usr/bin/env python3
"""Derive the RPM builder image's package list from the RPM sources.

The builder image carries everything the RPM harness installs before it
builds: the tool sets of the source builder and the companion builder
Containerfiles, the tools each per-SRPM rebuild layer installs, and every
``BuildRequires`` the companion specs and the Tongs spec templates declare.
A ``BuildRequires`` that only a source-built companion RPM provides is left
out, because Fedora does not ship it and each rebuild layer installs it from
the companion repository as before.

Version constraints are dropped: the image installs the current Fedora
build, and each rebuild layer still runs ``dnf builddep`` against its own
source RPM, which enforces every declared version.

``packages.txt`` next to this program is the committed result.  ``--check``
fails when it differs from what the sources declare; ``--write`` rewrites it.
The program is standard library only, because the builder workflow runs it on
the runner's Python before it installs anything.
"""

from __future__ import annotations

import argparse
import json
import re
import shlex
import sys
from collections.abc import Iterable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PACKAGE_LIST = Path(__file__).resolve().with_name("packages.txt")

#: Files whose ``dnf install`` commands name the harness tool sets.
TOOL_SOURCES = (
    "packaging/rpm/desktop/Containerfile",
    "packaging/rpm/python-dependencies/Containerfile",
    "packaging/rpm/desktop/rebuild_srpms.sh",
    "packaging/rpm/python-dependencies/rebuild_srpms.sh",
)
#: Spec files whose ``BuildRequires`` the image preinstalls.
SPEC_GLOBS = (
    "packaging/rpm/python-dependencies/specs/*.spec",
    "packaging/rpm/desktop/templates/*.spec.in",
)
COMPANION_MANIFEST = "packaging/rpm/python-dependencies/manifest.json"

HEADER = (
    "# Generated by packaging/rpm/builder/build_requires.py --write; do not edit.\n"
    "# The RPM tool sets and declared BuildRequires the builder image preinstalls.\n"
)

_BUILD_REQUIRES = re.compile(r"^BuildRequires:\s*(?P<value>.+?)\s*$")
_REQUIREMENT = re.compile(
    r"^(?P<name>[A-Za-z0-9][A-Za-z0-9_.+-]*(?:\([A-Za-z0-9_.+-]+\))?)"
    r"(?:\s*(?:>=|<=|=|>|<)\s*[A-Za-z0-9_.:~^+-]+)?$"
)
_PACKAGE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.+-]*(?:\([A-Za-z0-9_.+-]+\))?$")


def _normalize_distribution(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _joined_lines(text: str) -> list[str]:
    return text.replace("\\\n", " ").splitlines()


def dnf_install_packages(text: str, source: str) -> list[str]:
    """Return the packages every ``RUN dnf install`` command in ``text`` names."""

    packages: list[str] = []
    found = False
    for line in _joined_lines(text):
        stripped = line.strip()
        if not stripped.startswith("RUN dnf install "):
            continue
        found = True
        words = shlex.split(stripped[len("RUN ") :])
        for word in words[2:]:
            if word in {"&&", ";", "||", "|"}:
                break
            if word.startswith("-"):
                continue
            if not _PACKAGE.match(word):
                raise ValueError(f"{source}: unexpected dnf install word {word!r}")
            packages.append(word)
    if not found:
        raise ValueError(f"{source}: no RUN dnf install command found")
    return packages


def build_requires(text: str, source: str) -> list[str]:
    """Return the package names a spec's ``BuildRequires`` lines declare."""

    names: list[str] = []
    for line in text.splitlines():
        match = _BUILD_REQUIRES.match(line.strip())
        if not match:
            continue
        value = match.group("value")
        if "%" in value or "," in value:
            raise ValueError(f"{source}: unsupported BuildRequires {value!r}")
        requirement = _REQUIREMENT.match(value)
        if not requirement:
            raise ValueError(f"{source}: unparsable BuildRequires {value!r}")
        names.append(requirement.group("name"))
    if not names:
        raise ValueError(f"{source}: declares no BuildRequires")
    return names


def companion_provides(manifest: dict[str, object]) -> frozenset[str]:
    """Return the ``python3dist()`` names only source-built companions provide."""

    companions = manifest["companions"]
    if not isinstance(companions, list) or not companions:
        raise ValueError(f"{COMPANION_MANIFEST}: lists no companions")
    return frozenset(
        f"python3dist({_normalize_distribution(str(item['distribution']))})"
        for item in companions
    )


def _spec_paths(root: Path) -> list[Path]:
    paths = sorted(path for pattern in SPEC_GLOBS for path in root.glob(pattern))
    if not paths:
        raise ValueError("no RPM spec files found")
    return paths


def derive(root: Path = ROOT) -> list[str]:
    """Return the sorted, de-duplicated package list the sources declare."""

    packages: set[str] = set()
    for relative in TOOL_SOURCES:
        packages.update(dnf_install_packages((root / relative).read_text(), relative))
    excluded = companion_provides(json.loads((root / COMPANION_MANIFEST).read_text()))
    for path in _spec_paths(root):
        relative = path.relative_to(root).as_posix()
        for name in build_requires(path.read_text(), relative):
            if name not in excluded:
                packages.add(name)
    return sorted(packages)


def render(packages: Iterable[str]) -> str:
    return HEADER + "".join(f"{name}\n" for name in packages)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="fail when packages.txt differs from what the sources declare",
    )
    mode.add_argument(
        "--write", action="store_true", help="rewrite packages.txt from the sources"
    )
    arguments = parser.parse_args(argv)
    expected = render(derive())
    if arguments.write:
        PACKAGE_LIST.write_text(expected)
        return 0
    if arguments.check:
        current = PACKAGE_LIST.read_text() if PACKAGE_LIST.is_file() else ""
        if current != expected:
            print(
                "packaging/rpm/builder/packages.txt is stale; run "
                "packaging/rpm/builder/build_requires.py --write",
                file=sys.stderr,
            )
            return 1
        return 0
    sys.stdout.write(expected)
    return 0


if __name__ == "__main__":
    sys.exit(main())
